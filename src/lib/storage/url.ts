// Ownership checks for book image URLs.

export const BOOK_IMAGES_BUCKET = "book-images";

// Returns the object path inside the bucket ("{userId}/{bookId}/{uuid}.png")
// when a public URL points at the user's OWN folder, and null otherwise.
// Passing bookId narrows the scope to that book's folder.
//
// Used both when validating a URL before it is stored (so another user's image
// cannot be linked) and when deleting (so only the user's own files are
// touched). Two rules matter:
// - A plain startsWith() is not enough: ".../{userId}/{bookId}/../../{other}/x.png"
//   passes the prefix test, but resolving ".." (or "%2e%2e") lands on another
//   user's file. The URL is normalised first.
// - Paths containing "%" are rejected: the URL parser does not treat "%2F" as a
//   separator, yet a decoded path could become "a/../../{other}". File names
//   generated by the app (uuid plus extension) never contain escapes.
export function ownImagePath(
  value: string,
  userId: string,
  bookId?: string,
): string | null {
  const base = process.env.NEXT_PUBLIC_SUPABASE_URL;
  if (!base) return null;

  let url: URL;
  let root: URL;
  try {
    url = new URL(value);
    root = new URL(`/storage/v1/object/public/${BOOK_IMAGES_BUCKET}/`, base);
  } catch {
    return null;
  }

  const scope = bookId ? `${userId}/${bookId}/` : `${userId}/`;
  const expected = root.pathname + scope;

  if (
    url.origin !== root.origin ||
    url.search !== "" ||
    url.hash !== "" ||
    url.pathname.includes("%") ||
    !url.pathname.startsWith(expected) ||
    url.pathname.length <= expected.length
  ) {
    return null;
  }

  return url.pathname.slice(root.pathname.length);
}

// Does this cover/image URL belong to the user's folder for this book?
export function isOwnBookImageUrl(
  value: string,
  userId: string,
  bookId: string,
): boolean {
  return ownImagePath(value, userId, bookId) !== null;
}
